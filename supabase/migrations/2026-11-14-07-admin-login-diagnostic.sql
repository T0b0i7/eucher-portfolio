-- ============================================================================
-- Correctif connexion admin : diagnostic serveur, vérification d'identité
-- GitHub de secours, journal des tentatives. Rejouable.
-- ============================================================================

create table if not exists public.admin_login_log (
  id bigint generated by default as identity primary key,
  uid uuid,
  role text,
  login text,
  owner boolean,
  detail jsonb,
  created_at timestamptz not null default now()
);
alter table public.admin_login_log enable row level security;
revoke all on public.admin_login_log from anon, authenticated;

-- Le propriétaire est reconnu via public.admins OU via l'identité GitHub
-- vérifiée côté serveur (auth.identities n'est pas modifiable par l'utilisateur).
create or replace function public.is_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where uid = auth.uid())
      or exists (
        select 1 from auth.identities i
        where i.user_id = auth.uid()
          and i.provider = 'github'
          and lower(i.identity_data->>'user_name') = 't0b0i7'
      );
$$;

create or replace function public.admin_diag()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'uid', auth.uid(),
    'role', coalesce(current_setting('request.jwt.claim.role', true), ''),
    'sub', coalesce(current_setting('request.jwt.claim.sub', true), ''),
    'login', (
      select i.identity_data->>'user_name'
      from auth.identities i
      where i.user_id = auth.uid() and i.provider = 'github'
      limit 1
    ),
    'owner', public.is_owner(),
    'adminRows', (select count(*) from public.admins)
  );
$$;

create or replace function public.log_admin_attempt()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  d jsonb;
begin
  d := public.admin_diag();
  insert into public.admin_login_log (uid, role, login, owner, detail)
  values (
    case when coalesce(d->>'uid', '') ~ '^[0-9a-f-]{36}$' then (d->>'uid')::uuid end,
    d->>'role',
    d->>'login',
    coalesce((d->>'owner')::boolean, false),
    d
  );
  return d;
end;
$$;

grant execute on function public.admin_diag() to anon, authenticated;
grant execute on function public.log_admin_attempt() to anon, authenticated;
